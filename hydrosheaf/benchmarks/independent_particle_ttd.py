@dataclass(frozen=True)
class ParticleTTDRecovery:
    """Coarse public-data estimate or explicit abstention from the baseline."""

    status: str
    target_node_id: str
    primary_tracer: str
    young_water_fraction: float | None
    mean_lag_days: float | None
    fitted_lag_days: tuple[float, ...]
    fitted_mass: tuple[float, ...]
    source_weight: Mapping[str, float]
    predictions: tuple[FuturePrediction, ...]
    calibration_rmse: float | None
    n_calibration_samples: int
    reason: str | None
    used_input_ids: tuple[str, ...]
    sealed_commitment: str

    def __post_init__(self) -> None:
        if self.status not in {"ESTIMATED", "ABSTAIN"}:
            raise ValueError("Recovery status must be ESTIMATED or ABSTAIN.")
        if len(self.sealed_commitment) != 64:
            raise ValueError("Recovery must retain the observation commitment.")
        if self.status == "ESTIMATED":
            if self.young_water_fraction is None or self.mean_lag_days is None:
                raise ValueError("An estimate requires coarse young-water and mean-lag values.")
            if not 0.0 <= self.young_water_fraction <= 1.0:
                raise ValueError("Young-water fraction must be a probability.")
            if self.mean_lag_days < 0.0 or not self.fitted_mass:
                raise ValueError("An estimate requires a causal fitted distribution.")
        object.__setattr__(self, "fitted_lag_days", tuple(float(value) for value in self.fitted_lag_days))
        object.__setattr__(self, "fitted_mass", tuple(float(value) for value in self.fitted_mass))
        object.__setattr__(self, "source_weight", _frozen_float_mapping(self.source_weight))
        object.__setattr__(self, "predictions", tuple(self.predictions))
        object.__setattr__(self, "used_input_ids", tuple(self.used_input_ids))


