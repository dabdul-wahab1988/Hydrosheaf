def _particle_travel_times(
    rng: np.random.Generator,
    *,
    n_particles: int,
    shape: float,
    scale_days: float,
    fast_fraction: float,
    fast_scale_days: float,
) -> np.ndarray:
    """Sample a delayed gamma component plus a preferential fast component."""

    delayed = rng.gamma(shape=shape, scale=scale_days, size=n_particles)
    fast = rng.exponential(scale=fast_scale_days, size=n_particles)
    use_fast = rng.random(n_particles) < fast_fraction
    return np.where(use_fast, fast, delayed)


def _kernel_from_particles(
    edge: _EDGE,
    particle_times: np.ndarray,
    config: ParticleTTDConfig,
) -> EdgeParticleKernel:
    lag_days = np.arange(config.max_lag_steps + 1, dtype=float) * config.time_step_days
    bin_index = np.floor(particle_times / config.time_step_days).astype(int)
    # The terminal bin represents a declared tail bin rather than silently
    # dropping old particles; mass remains exactly conserved.
    bin_index = np.clip(bin_index, 0, config.max_lag_steps)
    counts = np.bincount(bin_index, minlength=config.max_lag_steps + 1).astype(float)
    mass = counts / float(counts.sum())
    return EdgeParticleKernel(
        edge=edge,
        particle_travel_times_days=particle_times,
        lag_days=lag_days,
        mass=mass,
    )


def _causal_convolution(signal: np.ndarray, mass: np.ndarray) -> np.ndarray:
    """Apply a normalized causal lag kernel to a finite input signal."""

    if signal.ndim != 1 or mass.ndim != 1:
        raise ValueError("Causal convolution expects one-dimensional arrays.")
    return np.convolve(signal, mass, mode="full")[: signal.size]


def _event_signal(
    time_days: np.ndarray,
    *,
    base: float,
    seasonal_amplitude: float,
    phase_days: float,
    event_scale: float,
) -> np.ndarray:
    """Seasonal forcing with several recharge-event pulses."""

    seasonal = seasonal_amplitude * np.sin(2.0 * np.pi * (time_days - phase_days) / 365.25)
    centres = (150.0, 510.0, 980.0, 1435.0)
    widths = (21.0, 32.0, 18.0, 38.0)
    amplitudes = (0.75, -0.55, 0.95, -0.45)
    events = sum(
        event_scale * amplitude * np.exp(-0.5 * ((time_days - centre) / width) ** 2)
        for centre, width, amplitude in zip(centres, widths, amplitudes, strict=True)
    )
    return base + seasonal + events


