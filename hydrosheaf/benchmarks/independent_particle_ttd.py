def _shift_and_attenuate(signal: np.ndarray, shift_steps: int = 8) -> np.ndarray:
    """Construct a public forcing error without accessing it in the estimator."""

    shifted = np.empty_like(signal)
    shifted[:shift_steps] = signal[0]
    shifted[shift_steps:] = signal[:-shift_steps]
    return 0.78 * shifted + 0.22 * float(np.mean(signal))


def _draw_sum_particles(
    rng: np.random.Generator,
    upstream_particles: np.ndarray,
    edge_particles: np.ndarray,
    n_particles: int,
) -> np.ndarray:
    return (
        upstream_particles[rng.integers(0, upstream_particles.size, size=n_particles)]
        + edge_particles[rng.integers(0, edge_particles.size, size=n_particles)]
    )


def _mix_particles(
    rng: np.random.Generator,
    contributions: Sequence[tuple[float, np.ndarray]],
    n_particles: int,
) -> np.ndarray:
    weights = np.asarray([weight for weight, _ in contributions], dtype=float)
    if np.any(weights < 0.0) or not np.isclose(float(weights.sum()), 1.0, atol=1e-12):
        raise ValueError("Particle mixing weights must be non-negative and mass conserving.")
    component = rng.choice(len(contributions), size=n_particles, p=weights)
    result = np.empty(n_particles, dtype=float)
    for index, (_, particles) in enumerate(contributions):
        selected = np.flatnonzero(component == index)
        if selected.size:
            result[selected] = particles[
                rng.integers(0, particles.size, size=selected.size)
            ]
    return result


def _true_network(
    rng: np.random.Generator,
    config: ParticleTTDConfig,
    control: _ScenarioControl,
) -> tuple[
    tuple[_EDGE, ...],
    Mapping[str, EdgeParticleKernel],
    Mapping[str, np.ndarray],
    Mapping[str, Mapping[str, float]],
    Mapping[str, float],
]:
    """Create raw-path truth for a branching/merging directed network."""

    edges: tuple[_EDGE, ...] = (
        ("source_north", "branch_a"),
        ("source_south", "branch_b"),
        ("branch_a", "merge"),
        ("branch_b", "merge"),
        ("merge", "well_terminal"),
        ("branch_a", "well_terminal"),
    )
    parameters = {
        ("source_north", "branch_a"): (3.4, 15.5, 0.12, 6.5),
        ("source_south", "branch_b"): (3.0, 21.5, 0.10, 8.0),
        ("branch_a", "merge"): (3.7, 18.5, 0.08, 7.5),
        ("branch_b", "merge"): (4.0, 24.5, 0.07, 9.5),
        ("merge", "well_terminal"): (4.2, 19.0, 0.10, 7.0),
        ("branch_a", "well_terminal"): (4.5, 24.0, 0.05, 9.0),
    }
    kernels: dict[str, EdgeParticleKernel] = {}
    for edge in edges:
        shape, scale, fast_fraction, fast_scale = parameters[edge]
        particles = _particle_travel_times(
            rng,
            n_particles=config.n_particles,
            shape=shape,
            scale_days=scale,
            fast_fraction=fast_fraction,
            fast_scale_days=fast_scale,
        )
        kernels[_edge_id(edge)] = _kernel_from_particles(edge, particles, config)

    local_fraction = {
        "merge": 0.20,
        "well_terminal": control.terminal_local_fraction,
    }
    merge_weights = {"local:merge": 0.20, "branch_a": 0.46, "branch_b": 0.34}
    terminal_nonlocal = 1.0 - control.terminal_local_fraction
    terminal_weights = {
        "local:well_terminal": control.terminal_local_fraction,
        "merge": 0.74 * terminal_nonlocal,
        "branch_a": 0.26 * terminal_nonlocal,
    }
    upstream = {"merge": merge_weights, "well_terminal": terminal_weights}

    zero = np.zeros(config.n_particles, dtype=float)
    node_particles: dict[str, np.ndarray] = {
        "source_north": zero.copy(),
        "source_south": zero.copy(),
    }
    node_particles["branch_a"] = kernels[_edge_id(("source_north", "branch_a"))].particle_travel_times_days.copy()
    node_particles["branch_b"] = kernels[_edge_id(("source_south", "branch_b"))].particle_travel_times_days.copy()

    via_a_merge = _draw_sum_particles(
        rng,
        node_particles["branch_a"],
        kernels[_edge_id(("branch_a", "merge"))].particle_travel_times_days,
        config.n_particles,
    )
    via_b_merge = _draw_sum_particles(
        rng,
        node_particles["branch_b"],
        kernels[_edge_id(("branch_b", "merge"))].particle_travel_times_days,
        config.n_particles,
    )
    node_particles["merge"] = _mix_particles(
        rng,
        ((merge_weights["local:merge"], zero), (merge_weights["branch_a"], via_a_merge), (merge_weights["branch_b"], via_b_merge)),
        config.n_particles,
    )

    via_merge_terminal = _draw_sum_particles(
        rng,
        node_particles["merge"],
        kernels[_edge_id(("merge", "well_terminal"))].particle_travel_times_days,
        config.n_particles,
    )
    via_a_terminal = _draw_sum_particles(
        rng,
        node_particles["branch_a"],
        kernels[_edge_id(("branch_a", "well_terminal"))].particle_travel_times_days,
        config.n_particles,
    )
    node_particles["well_terminal"] = _mix_particles(
        rng,
        (
            (terminal_weights["local:well_terminal"], zero),
            (terminal_weights["merge"], via_merge_terminal),
            (terminal_weights["branch_a"], via_a_terminal),
        ),
        config.n_particles,
    )
    return edges, kernels, node_particles, upstream, local_fraction


def _forward_node_responses(
    inputs: Mapping[str, Mapping[str, np.ndarray]],
    kernels: Mapping[str, EdgeParticleKernel],
    local_fraction: Mapping[str, float],
) -> Mapping[str, Mapping[str, np.ndarray]]:
    """Forward particle-histogram transport with explicit local mixing terms."""

    response: dict[str, dict[str, np.ndarray]] = {}

    def kernel(start: str, end: str) -> np.ndarray:
        return kernels[_edge_id((start, end))].mass

    for tracer, forcing in inputs.items():
        north = np.asarray(forcing["recharge:north"], dtype=float)
        south = np.asarray(forcing["recharge:south"], dtype=float)
        branch_a = _causal_convolution(north, kernel("source_north", "branch_a"))
        branch_b = _causal_convolution(south, kernel("source_south", "branch_b"))
        merge = (
            local_fraction["merge"] * np.asarray(forcing["local:merge"], dtype=float)
            + 0.46 * _causal_convolution(branch_a, kernel("branch_a", "merge"))
            + 0.34 * _causal_convolution(branch_b, kernel("branch_b", "merge"))
        )
        terminal_nonlocal = 1.0 - local_fraction["well_terminal"]
        terminal = (
            local_fraction["well_terminal"]
            * np.asarray(forcing["local:well_terminal"], dtype=float)
            + 0.74 * terminal_nonlocal * _causal_convolution(merge, kernel("merge", "well_terminal"))
            + 0.26 * terminal_nonlocal * _causal_convolution(branch_a, kernel("branch_a", "well_terminal"))
        )
        response[tracer] = {
            "source_north": north,
            "source_south": south,
            "branch_a": branch_a,
            "branch_b": branch_b,
            "merge": merge,
            "well_terminal": terminal,
        }
    return response


def _candidate_edges(true_edges: Sequence[_EDGE], candidate_mode: str) -> tuple[_EDGE, ...]:
    if candidate_mode == "near_correct":
        # A declared extra edge makes the nominal setting a candidate-graph
        # problem rather than an oracle graph problem.
        return tuple(true_edges) + (("branch_b", "well_terminal"),)
    if candidate_mode == "reversed_terminal_connection":
        retained = tuple(
            edge
            for edge in true_edges
            if edge not in {("merge", "well_terminal"), ("branch_a", "well_terminal")}
        )
        return retained + (
            ("well_terminal", "merge"),
            ("well_terminal", "branch_a"),
            ("branch_b", "well_terminal"),
        )
    raise ValueError(f"Unknown candidate mode {candidate_mode!r}.")


def _irregular_indices(
    rng: np.random.Generator,
    candidates: np.ndarray,
    *,
    keep_probability: float,
    minimum: int,
) -> np.ndarray:
    selected = candidates[rng.random(candidates.size) < keep_probability]
    if selected.size < minimum:
        remaining = np.setdiff1d(candidates, selected, assume_unique=True)
        take = min(max(minimum - selected.size, 0), remaining.size)
        if take:
            selected = np.concatenate((selected, rng.choice(remaining, size=take, replace=False)))
    return np.sort(selected.astype(int))


def _visible_forcing(
    inputs: Mapping[str, Mapping[str, np.ndarray]],
    mode: str,
) -> Mapping[str, Mapping[str, np.ndarray]]:
    if mode == "matched":
        return inputs
    if mode == "phase_shifted_attenuated":
        return {
            tracer: {input_id: _shift_and_attenuate(values) for input_id, values in per_input.items()}
            for tracer, per_input in inputs.items()
        }
    raise ValueError(f"Unknown visible forcing mode {mode!r}.")


def _truth_commitment(truth: ParticleTTDTruth) -> str:
    hasher = hashlib.sha256()
    hasher.update(PARTICLE_TTD_GENERATOR_VERSION.encode("ascii"))
    hasher.update(_canonical_json({
        "seed": truth.config.seed,
        "scenario": truth.config.scenario,
        "n_particles": truth.config.n_particles,
        "n_steps": truth.config.n_steps,
        "time_step_days": truth.config.time_step_days,
        "max_lag_steps": truth.config.max_lag_steps,
    }).encode("utf-8"))
    for edge in sorted(truth.true_edges):
        kernel = truth.edge_kernels[_edge_id(edge)]
        hasher.update(_edge_id(edge).encode("utf-8"))
        _array_digest(hasher, "edge_particles", kernel.particle_travel_times_days)
        _array_digest(hasher, "edge_lags", kernel.lag_days)
        _array_digest(hasher, "edge_mass", kernel.mass)
    for node in sorted(truth.node_age_particles):
        _array_digest(hasher, f"node_age:{node}", truth.node_age_particles[node])
    for tracer in sorted(truth.node_responses):
        for node in sorted(truth.node_responses[tracer]):
            _array_digest(hasher, f"response:{tracer}:{node}", truth.node_responses[tracer][node])
    for tracer in sorted(truth.input_signals):
        for input_id in sorted(truth.input_signals[tracer]):
            _array_digest(hasher, f"input:{tracer}:{input_id}", truth.input_signals[tracer][input_id])
    hasher.update(_canonical_json(dict(truth.local_recharge_fraction)).encode("utf-8"))
    hasher.update(
        _canonical_json({node: dict(weights) for node, weights in truth.upstream_mixing_fraction.items()}).encode("utf-8")
    )
    return hasher.hexdigest()


def _build_public_observations(
    rng: np.random.Generator,
    *,
    config: ParticleTTDConfig,
    control: _ScenarioControl,
    true_edges: Sequence[_EDGE],
    inputs: Mapping[str, Mapping[str, np.ndarray]],
    responses: Mapping[str, Mapping[str, np.ndarray]],
    commitment: str,
) -> ParticleTTDObservations:
    """Sample the public input/output view while keeping future outputs sealed."""

    visible = _visible_forcing(inputs, control.visible_forcing_mode)
    input_nodes = {
        "recharge:north": "source_north",
        "recharge:south": "source_south",
        "local:merge": "merge",
        "local:well_terminal": "well_terminal",
    }
    exposed_ids = tuple(input_nodes)
    if not control.expose_local_forcing:
        exposed_ids = tuple(item for item in exposed_ids if not item.startswith("local:"))

    time_days = np.arange(config.n_steps, dtype=float) * config.time_step_days
    forcing_rows: list[ForcingObservation] = []
    forcing_candidates = np.arange(config.n_steps, dtype=int)
    for tracer in _TRACERS:
        for input_id in exposed_ids:
            indices = _irregular_indices(
                rng,
                forcing_candidates,
                keep_probability=control.input_keep_probability,
                minimum=max(12, config.minimum_calibration_points),
            )
            noise = rng.normal(0.0, config.input_noise_std, size=indices.size)
            values = visible[tracer][input_id][indices] + noise
            forcing_rows.extend(
                ForcingObservation(
                    input_id=input_id,
                    node_id=input_nodes[input_id],
                    tracer=tracer,
                    time_index=int(index),
                    time_days=float(time_days[index]),
                    value=float(value),
                )
                for index, value in zip(indices, values, strict=True)
            )

    calibration_end = int(config.n_steps * config.calibration_fraction)
    # We do not offer finite-horizon outputs during kernel warm-up; this avoids
    # pretending the source history before virtual time zero was observed.
    calibration_candidates = np.arange(config.max_lag_steps, calibration_end, dtype=int)
    output_rows: list[OutputObservation] = []
    node_ids = ("branch_a", "branch_b", "merge", "well_terminal")
    for tracer in _TRACERS:
        for node_id in node_ids:
            if node_id == "well_terminal" and config.scenario == "sparse":
                count = min(6, calibration_candidates.size)
                indices = np.sort(rng.choice(calibration_candidates, size=count, replace=False))
            else:
                indices = _irregular_indices(
                    rng,
                    calibration_candidates,
                    keep_probability=control.output_keep_probability,
                    minimum=config.minimum_calibration_points,
                )
            sigma = config.output_noise_std * (1.15 if tracer == "d18O" else 0.85)
            noisy = responses[tracer][node_id][indices] + rng.normal(0.0, sigma, size=indices.size)
            output_rows.extend(
                OutputObservation(
                    node_id=node_id,
                    tracer=tracer,
                    time_index=int(index),
                    time_days=float(time_days[index]),
                    value=float(value),
                )
                for index, value in zip(indices, noisy, strict=True)
            )

    future_candidates = np.arange(calibration_end, config.n_steps, dtype=int)
    future_indices = _irregular_indices(
        rng,
        future_candidates,
        keep_probability=0.72,
        minimum=min(12, future_candidates.size),
    )
    future_targets = tuple(
        FutureTarget(
            node_id="well_terminal",
            tracer=config.primary_tracer,
            time_index=int(index),
            time_days=float(time_days[index]),
        )
        for index in future_indices
    )
    provenance = dict(independent_particle_generator_provenance())
    provenance.update(
        {
            "seed": config.seed,
            "scenario": config.scenario,
            "visible_forcing_mode": control.visible_forcing_mode,
            "local_forcing_exposed": control.expose_local_forcing,
            "calibration_end_index": calibration_end,
            "future_outputs_withheld": True,
            "missing_values_are_absent_rows": True,
        }
    )
    return ParticleTTDObservations(
        candidate_edges=_candidate_edges(true_edges, control.candidate_mode),
        forcing_node_ids={key: input_nodes[key] for key in exposed_ids},
        forcing_samples=tuple(forcing_rows),
        calibration_samples=tuple(output_rows),
        future_targets=future_targets,
        target_node_id="well_terminal",
        primary_tracer=config.primary_tracer,
        time_step_days=config.time_step_days,
        lag_window_steps=config.max_lag_steps,
        young_threshold_days=config.young_threshold_days,
        scenario=config.scenario,
        declared_stressors=control.stressors,
        sealed_commitment=commitment,
        provenance=provenance,
    )


def generate_independent_particle_ttd_case(
    config: ParticleTTDConfig | None = None,
) -> ParticleTTDCase:
    """Generate one deterministic, sealed, branch-and-merge particle case."""

    assert_independent_particle_generator()
    config = config or ParticleTTDConfig()
    control = _scenario_control(config.scenario)
    rng = np.random.default_rng(config.seed)
    true_edges, edge_kernels, node_particles, upstream, local_fraction = _true_network(rng, config, control)
    inputs = _input_signal_truth(config)
    responses = _forward_node_responses(inputs, edge_kernels, local_fraction)
    provenance = dict(independent_particle_generator_provenance())
    provenance.update(
        {
            "seed": config.seed,
            "scenario": config.scenario,
            "particle_count_per_edge": config.n_particles,
            "network_structure": "two_sources_branch_merge_with_shortcut_and_local_recharge",
            "holdout_policy": "future_terminal_response_values_are_scoring_only",
        }
    )
    provisional_truth = ParticleTTDTruth(
        config=config,
        true_edges=true_edges,
        edge_kernels=edge_kernels,
        node_age_particles=node_particles,
        node_responses=responses,
        input_signals=inputs,
        local_recharge_fraction=local_fraction,
        upstream_mixing_fraction=upstream,
        commitment="0" * 64,
        provenance=provenance,
    )
    truth = replace(provisional_truth, commitment=_truth_commitment(provisional_truth))
    observations = _build_public_observations(
        rng,
        config=config,
        control=control,
        true_edges=true_edges,
        inputs=inputs,
        responses=responses,
        commitment=truth.commitment,
    )
    assert_particle_observation_view_is_truth_blind(observations)
    return ParticleTTDCase(observations=observations, truth=truth)


# A concise alias makes the generator discoverable without compromising its
# explicit independent-family name.
generate_particle_ttd_case = generate_independent_particle_ttd_case


def _forbidden_name(name: str) -> bool:
    lowered = name.lower()
    return lowered.startswith("true_") or lowered.startswith("truth_")


def _assert_no_truth_fields(value: Any, *, path: str = "observation") -> None:
    """Reject latent-state fields before an inference calculation begins."""

    if isinstance(value, Mapping):
        for key, nested in value.items():
            key_text = str(key)
            if _forbidden_name(key_text):
                raise ValueError(f"Inference-visible input contains forbidden latent field {path}.{key_text}.")
            _assert_no_truth_fields(nested, path=f"{path}.{key_text}")
    elif is_dataclass(value):
        for item in fields(value):
            if _forbidden_name(item.name):
                raise ValueError(f"Inference-visible object contains forbidden latent field {path}.{item.name}.")
            _assert_no_truth_fields(getattr(value, item.name), path=f"{path}.{item.name}")
    elif isinstance(value, (tuple, list)):
        for index, nested in enumerate(value):
            _assert_no_truth_fields(nested, path=f"{path}[{index}]")


def assert_particle_observation_view_is_truth_blind(
    observations: ParticleTTDObservations | Mapping[str, object],
) -> None:
    """Assert that an estimator can see no fields named as latent truth."""

    _assert_no_truth_fields(observations)
    if isinstance(observations, ParticleTTDObservations):
        if observations.future_targets and any(
            target.time_index
            <= max(sample.time_index for sample in observations.calibration_samples)
            for target in observations.future_targets
        ):
            raise ValueError("Future holdout targets must be strictly after calibration outputs.")


def particle_ttd_public_manifest(observations: ParticleTTDObservations) -> Mapping[str, object]:
    """Return a serializable manifest that deliberately omits all latent values."""

    assert_particle_observation_view_is_truth_blind(observations)
    return MappingProxyType(
        {
            "generator_provenance": dict(observations.provenance),
            "sealed_commitment": observations.sealed_commitment,
            "candidate_edges": [list(edge) for edge in observations.candidate_edges],
            "forcing_samples": len(observations.forcing_samples),
            "calibration_samples": len(observations.calibration_samples),
            "future_targets": len(observations.future_targets),
            "scenario": observations.scenario,
            "declared_stressors": list(observations.declared_stressors),
            "evidence_scope": "controlled_synthetic_only",
        }
    )


def _path_exists(edges: Iterable[_EDGE], start: str, end: str) -> bool:
    if start == end:
        return True
    adjacency: dict[str, set[str]] = {}
    for source, target in edges:
        adjacency.setdefault(source, set()).add(target)
    queue = [start]
    visited = {start}
    while queue:
        current = queue.pop(0)
        for next_node in adjacency.get(current, ()):
            if next_node == end:
                return True
            if next_node not in visited:
                visited.add(next_node)
                queue.append(next_node)
    return False


def _interpolate_forcing(
    rows: Sequence[ForcingObservation],
    *,
    input_id: str,
    tracer: str,
    n_steps: int,
) -> np.ndarray | None:
    selected = sorted(
        (row for row in rows if row.input_id == input_id and row.tracer == tracer),
        key=lambda row: row.time_index,
    )
    if len(selected) < 3:
        return None
    index = np.asarray([row.time_index for row in selected], dtype=int)
    values = np.asarray([row.value for row in selected], dtype=float)
    # A row is either present with a measured value or absent; no missing tracer
    # value is imputed as zero before this explicitly declared interpolation.
    unique_index, unique_position = np.unique(index, return_index=True)
    if unique_index.size < 3:
        return None
    return np.interp(np.arange(n_steps, dtype=float), unique_index, values[unique_position])


def _lagged_series(values: np.ndarray, lag: int) -> np.ndarray:
    result = np.zeros_like(values, dtype=float)
    if lag == 0:
        result[:] = values
    else:
        result[lag:] = values[:-lag]
    return result


def _abstain(
    observations: ParticleTTDObservations,
    *,
    reason: str,
    n_calibration_samples: int,
    used_input_ids: Sequence[str] = (),
) -> ParticleTTDRecovery:
    return ParticleTTDRecovery(
        status="ABSTAIN",
        target_node_id=observations.target_node_id,
        primary_tracer=observations.primary_tracer,
        young_water_fraction=None,
        mean_lag_days=None,
        fitted_lag_days=(),
        fitted_mass=(),
        source_weight={},
        predictions=(),
        calibration_rmse=None,
        n_calibration_samples=n_calibration_samples,
        reason=reason,
        used_input_ids=tuple(used_input_ids),
        sealed_commitment=observations.sealed_commitment,
    )


def recover_particle_ttd_baseline(observations: ParticleTTDObservations) -> ParticleTTDRecovery:
    """Fit a deliberately simple, truth-blind coarse lag/mixing baseline.

    The estimator sees public candidate edges and public forcing/output rows
    only.  It forms non-negative coarse lag masses from a least-squares fit.
    It intentionally does not use a hidden edge kernel, hidden response, or
    any private particle attribute; sparse cases return ``ABSTAIN`` instead of
    manufacturing a precise age estimate.
    """

    if not isinstance(observations, ParticleTTDObservations):
        raise TypeError("Particle baseline requires ParticleTTDObservations only.")
    assert_particle_observation_view_is_truth_blind(observations)
    tracer = observations.primary_tracer
    target_rows = sorted(
        (
            row
            for row in observations.calibration_samples
            if row.node_id == observations.target_node_id and row.tracer == tracer
        ),
        key=lambda row: row.time_index,
    )
    if len(target_rows) < 8:
        return _abstain(
            observations,
            reason="insufficient_calibration_observations",
            n_calibration_samples=len(target_rows),
        )
    if len(target_rows) < max(8, int(observations.provenance.get("minimum_calibration_points", 18))):
        return _abstain(
            observations,
            reason="insufficient_calibration_observations",
            n_calibration_samples=len(target_rows),
        )

    n_steps = max(
        [row.time_index for row in observations.forcing_samples]
        + [target.time_index for target in observations.future_targets]
        + [row.time_index for row in target_rows]
    ) + 1
    usable_inputs: list[tuple[str, np.ndarray]] = []
    for input_id, node_id in sorted(observations.forcing_node_ids.items()):
        if not _path_exists(observations.candidate_edges, node_id, observations.target_node_id):
            continue
        interpolated = _interpolate_forcing(
            observations.forcing_samples,
            input_id=input_id,
            tracer=tracer,
            n_steps=n_steps,
        )
        if interpolated is not None and float(np.std(interpolated)) > 1e-8:
            usable_inputs.append((input_id, interpolated))
    if not usable_inputs:
        return _abstain(
            observations,
            reason="no_candidate_recharge_path_with_observed_forcing",
            n_calibration_samples=len(target_rows),
        )

    observation_index = np.asarray([row.time_index for row in target_rows], dtype=int)
    observed_values = np.asarray([row.value for row in target_rows], dtype=float)
    lag_stride = 3
    lag_steps = np.arange(0, observations.lag_window_steps + 1, lag_stride, dtype=int)
    columns: list[np.ndarray] = []
    feature_labels: list[tuple[str, int]] = []
    normalised: dict[str, np.ndarray] = {}
    for input_id, series in usable_inputs:
        reference = series[observation_index]
        centre = float(np.mean(reference))
        scale = float(np.std(reference))
        if scale <= 1e-8:
            continue
        standard = (series - centre) / scale
        normalised[input_id] = standard
        for lag in lag_steps:
            columns.append(_lagged_series(standard, int(lag))[observation_index])
            feature_labels.append((input_id, int(lag)))
    if not columns:
        return _abstain(
            observations,
            reason="forcing_has_no_variation_after_public_interpolation",
            n_calibration_samples=len(target_rows),
            used_input_ids=tuple(input_id for input_id, _ in usable_inputs),
        )
    design = np.column_stack(columns)
    centred_output = observed_values - float(np.mean(observed_values))
    # This is a simple public baseline, not the proposed HydroSheaf inverse.
    # A small deterministic ridge stabilises irregular underdetermined designs.
    ridge = 1e-3
    augmented_design = np.vstack((design, np.sqrt(ridge) * np.eye(design.shape[1])))
    augmented_output = np.concatenate((centred_output, np.zeros(design.shape[1], dtype=float)))
    coefficients = np.linalg.lstsq(augmented_design, augmented_output, rcond=None)[0]
    coefficients = np.maximum(coefficients, 0.0)
    coefficient_sum = float(coefficients.sum())
    if coefficient_sum <= 1e-10:
        return _abstain(
            observations,
            reason="no_nonnegative_lag_signal_supported_by_public_data",
            n_calibration_samples=len(target_rows),
            used_input_ids=tuple(normalised),
        )

    mass_by_lag = np.zeros(lag_steps.size, dtype=float)
    mass_by_input: dict[str, float] = {input_id: 0.0 for input_id in normalised}
    for coefficient, (input_id, lag) in zip(coefficients, feature_labels, strict=True):
        position = int(np.where(lag_steps == lag)[0][0])
        mass_by_lag[position] += coefficient
        mass_by_input[input_id] += float(coefficient)
    mass_by_lag /= float(mass_by_lag.sum())
    lag_days = lag_steps.astype(float) * observations.time_step_days
    young = float(mass_by_lag[lag_days <= observations.young_threshold_days].sum())
    mean_lag = float(np.dot(mass_by_lag, lag_days))
    calibration_prediction = float(np.mean(observed_values)) + design @ coefficients
    calibration_rmse = float(np.sqrt(np.mean((calibration_prediction - observed_values) ** 2)))

    predictions: list[FuturePrediction] = []
    for target in observations.future_targets:
        if target.node_id != observations.target_node_id or target.tracer != tracer:
            continue
        features: list[float] = []
        for input_id, lag in feature_labels:
            series = normalised[input_id]
            index = target.time_index - lag
            features.append(float(series[index]) if index >= 0 else 0.0)
        predicted = float(np.mean(observed_values) + np.dot(np.asarray(features), coefficients))
        predictions.append(
            FuturePrediction(
                node_id=target.node_id,
                tracer=target.tracer,
                time_index=target.time_index,
                time_days=target.time_days,
                predicted_value=predicted,
            )
        )
    source_weight = {
        input_id: value / coefficient_sum for input_id, value in mass_by_input.items() if value > 0.0
    }
    return ParticleTTDRecovery(
        status="ESTIMATED",
        target_node_id=observations.target_node_id,
        primary_tracer=tracer,
        young_water_fraction=young,
        mean_lag_days=mean_lag,
        fitted_lag_days=tuple(float(value) for value in lag_days),
        fitted_mass=tuple(float(value) for value in mass_by_lag),
        source_weight=source_weight,
        predictions=tuple(predictions),
        calibration_rmse=calibration_rmse,
        n_calibration_samples=len(target_rows),
        reason=None,
        used_input_ids=tuple(normalised),
        sealed_commitment=observations.sealed_commitment,
    )


def score_particle_ttd_recovery(
    case: ParticleTTDCase,
    recovery: ParticleTTDRecovery,
) -> ParticleTTDScore:
    """Reveal sealed truth only after scoring a fixed recovery object."""

    if recovery.sealed_commitment != case.observations.sealed_commitment:
        raise ValueError("Recovery commitment does not match the public observation case.")
    verified = (
        case.truth.commitment == case.observations.sealed_commitment
        and case.truth.commitment == _truth_commitment(case.truth)
    )
    if not verified:
        raise ValueError("Sealed truth commitment does not verify.")
    particle_ages = case.truth.node_age_particles[recovery.target_node_id]
    young_truth = float(np.mean(particle_ages <= case.observations.young_threshold_days))
    mean_truth = float(np.mean(particle_ages))
    expected_abstention = _scenario_control(case.observations.scenario).expected_abstention
    if recovery.status == "ABSTAIN":
        return ParticleTTDScore(
            scenario=case.observations.scenario,
            commitment_verified=True,
            status=recovery.status,
            young_water_truth=young_truth,
            mean_lag_truth_days=mean_truth,
            young_water_absolute_error=None,
            mean_lag_absolute_error_days=None,
            held_out_rmse=None,
            n_held_out=len(case.observations.future_targets),
            appropriate_abstention=expected_abstention,
        )
    predicted = {prediction.time_index: prediction.predicted_value for prediction in recovery.predictions}
    target_indices = [
        target.time_index
        for target in case.observations.future_targets
        if target.node_id == recovery.target_node_id and target.tracer == recovery.primary_tracer
    ]
    paired_indices = [index for index in target_indices if index in predicted]
    if paired_indices:
        actual = np.asarray(
            [case.truth.node_responses[recovery.primary_tracer][recovery.target_node_id][index] for index in paired_indices],
            dtype=float,
        )
        estimated = np.asarray([predicted[index] for index in paired_indices], dtype=float)
        held_out_rmse: float | None = float(np.sqrt(np.mean((estimated - actual) ** 2)))
    else:
        held_out_rmse = None
    return ParticleTTDScore(
        scenario=case.observations.scenario,
        commitment_verified=True,
        status=recovery.status,
        young_water_truth=young_truth,
        mean_lag_truth_days=mean_truth,
        young_water_absolute_error=abs(float(recovery.young_water_fraction) - young_truth),
        mean_lag_absolute_error_days=abs(float(recovery.mean_lag_days) - mean_truth),
        held_out_rmse=held_out_rmse,
        n_held_out=len(paired_indices),
        appropriate_abstention=not expected_abstention,
    )


def run_independent_particle_ttd_stress_suite(
    *,
    seed: int = 1729,
    n_particles: int = 1_200,
    n_steps: int = 220,
    max_lag_steps: int = 48,
) -> tuple[ParticleTTDScenarioRun, ...]:
    """Run all predeclared particle-family stress scenarios without pooling claims."""

    runs: list[ParticleTTDScenarioRun] = []
    for offset, scenario in enumerate(_SCENARIOS):
        case = generate_independent_particle_ttd_case(
            ParticleTTDConfig(
                seed=seed + offset,
                scenario=scenario,
                n_particles=n_particles,
                n_steps=n_steps,
                max_lag_steps=max_lag_steps,
            )
        )
        recovery = recover_particle_ttd_baseline(case.observations)
        score = score_particle_ttd_recovery(case, recovery)
        runs.append(ParticleTTDScenarioRun(case=case, recovery=recovery, score=score))
    return tuple(runs)


