@dataclass(frozen=True)
class ParticleTTDObservations:
    """The complete inference-visible view, without latent transport truth."""

    candidate_edges: tuple[_EDGE, ...]
    forcing_node_ids: Mapping[str, str]
    forcing_samples: tuple[ForcingObservation, ...]
    calibration_samples: tuple[OutputObservation, ...]
    future_targets: tuple[FutureTarget, ...]
    target_node_id: str
    primary_tracer: str
    time_step_days: float
    lag_window_steps: int
    young_threshold_days: float
    scenario: str
    declared_stressors: tuple[str, ...]
    sealed_commitment: str
    provenance: Mapping[str, object] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.candidate_edges:
            raise ValueError("At least one candidate edge is required.")
        if self.primary_tracer not in _TRACERS:
            raise ValueError("Observation primary tracer is unsupported.")
        if self.time_step_days <= 0.0 or self.lag_window_steps <= 0:
            raise ValueError("Observation time discretisation must be positive.")
        if self.young_threshold_days <= 0.0 or self.scenario not in _SCENARIOS:
            raise ValueError("Observation metadata is invalid.")
        if len(self.sealed_commitment) != 64:
            raise ValueError("Observation view requires a sealed SHA-256 commitment.")
        candidate = tuple((str(start), str(end)) for start, end in self.candidate_edges)
        object.__setattr__(self, "candidate_edges", candidate)
        object.__setattr__(self, "forcing_node_ids", MappingProxyType(dict(self.forcing_node_ids)))
        object.__setattr__(self, "forcing_samples", tuple(self.forcing_samples))
        object.__setattr__(self, "calibration_samples", tuple(self.calibration_samples))
        object.__setattr__(self, "future_targets", tuple(self.future_targets))
