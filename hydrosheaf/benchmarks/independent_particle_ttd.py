"""Independent particle-network virtual generator for graph-TTD benchmarks.

This module is deliberately a *second* generator family.  It has no imports
from HydroSheaf's inverse, TTD, or benchmark implementations: transport truth
is generated by Monte-Carlo particle paths and then discretised only for the
forward observation model.  Consequently, a method evaluated against it does
not merely invert the same analytic forward model that created its data.

The generator is a controlled-synthetic instrument, not a field-validation
claim.  It produces a directed branch-and-merge groundwater network with
seasonal/event-like recharge forcing, local recharge, source mixing, irregular
noisy observations, and an output-only future holdout.  Latent truth and the
inference-visible observation view are intentionally separate dataclasses.
"""

from __future__ import annotations

import ast
from dataclasses import dataclass, field, fields, is_dataclass, replace
import hashlib
import json
from pathlib import Path
from types import MappingProxyType
from typing import Any, Iterable, Mapping, Sequence

import numpy as np


PARTICLE_TTD_GENERATOR_VERSION = "1.0.0"
PARTICLE_TTD_GENERATOR_FAMILY = "independent_particle_transport_network"
_EDGE = tuple[str, str]
_TRACERS = ("d18O", "conservative")
_SCENARIOS = (
    "nominal",
    "sparse",
    "wrong_forcing",
    "local_recharge_misspecification",
    "wrong_topology",
)


def _readonly(values: Sequence[float] | np.ndarray, *, dtype: Any = float) -> np.ndarray:
    """Return a copied, finite, read-only one-dimensional array."""

    array = np.asarray(values, dtype=dtype).copy()
    if array.ndim != 1:
        raise ValueError("Expected a one-dimensional numerical array.")
    if not np.all(np.isfinite(array)):
        raise ValueError("Particle benchmark arrays must be finite.")
    array.setflags(write=False)
    return array


def _frozen_float_mapping(values: Mapping[str, float]) -> Mapping[str, float]:
    converted = {str(key): float(value) for key, value in values.items()}
    if not all(np.isfinite(value) for value in converted.values()):
        raise ValueError("Mapping values must be finite.")
    return MappingProxyType(converted)


def _frozen_nested_array_mapping(
    values: Mapping[str, Mapping[str, Sequence[float] | np.ndarray]],
) -> Mapping[str, Mapping[str, np.ndarray]]:
    return MappingProxyType(
        {
            str(outer): MappingProxyType(
                {str(inner): _readonly(array) for inner, array in inner_values.items()}
            )
            for outer, inner_values in values.items()
        }
    )


def _array_digest(hasher: Any, label: str, values: np.ndarray) -> None:
    canonical = np.ascontiguousarray(values, dtype=float)
    hasher.update(label.encode("utf-8"))
    hasher.update(str(canonical.shape).encode("ascii"))
    hasher.update(canonical.tobytes())


def _canonical_json(payload: Any) -> str:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def _edge_id(edge: _EDGE) -> str:
    return f"{edge[0]}->{edge[1]}"


def _source_sha256() -> str:
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def independent_particle_generator_provenance() -> Mapping[str, object]:
    """Return auditable provenance for this intentionally independent family."""

    return MappingProxyType(
        {
            "generator_family": PARTICLE_TTD_GENERATOR_FAMILY,
            "generator_version": PARTICLE_TTD_GENERATOR_VERSION,
            "source_sha256": _source_sha256(),
            "imports_hydrosheaf": False,
            "independent_from_hydrosheaf_inference": True,
            "forward_representation": "particle_paths_then_causal_histogram",
            "evidence_scope": "controlled_synthetic_only",
        }
    )


def assert_independent_particle_generator() -> None:
    """Fail if this generator ever starts importing HydroSheaf implementation code.

    Keeping this guard in the module turns the intended independence boundary
    into an executable contract rather than a comment in a protocol.
    """

    parsed = ast.parse(Path(__file__).read_text(encoding="utf-8"))
    forbidden: list[str] = []
    for node in ast.walk(parsed):
        if isinstance(node, ast.Import):
            forbidden.extend(
                alias.name for alias in node.names if alias.name.startswith("hydrosheaf")
            )
        elif isinstance(node, ast.ImportFrom) and node.module:
            if node.module.startswith("hydrosheaf"):
                forbidden.append(node.module)
    if forbidden:
        raise RuntimeError(
            "Independent particle generator must not import HydroSheaf modules: "
            + ", ".join(sorted(set(forbidden)))
        )


@dataclass(frozen=True)
class ParticleTTDConfig:
    """Configuration for one sealed particle-network virtual case."""

    seed: int = 1729
    scenario: str = "nominal"
    n_particles: int = 2_000
    n_steps: int = 260
    time_step_days: float = 7.0
    max_lag_steps: int = 60
    calibration_fraction: float = 0.70
    primary_tracer: str = "d18O"
    young_threshold_days: float = 140.0
    input_noise_std: float = 0.04
    output_noise_std: float = 0.09
    minimum_calibration_points: int = 18

    def __post_init__(self) -> None:
        if self.scenario not in _SCENARIOS:
            raise ValueError(f"Unknown particle TTD scenario {self.scenario!r}.")
        if self.n_particles < 200:
            raise ValueError("n_particles must be at least 200.")
        if self.n_steps < 120:
            raise ValueError("n_steps must be at least 120 for a future holdout.")
        if self.time_step_days <= 0.0:
            raise ValueError("time_step_days must be positive.")
        if self.max_lag_steps < 8 or self.max_lag_steps >= self.n_steps // 2:
            raise ValueError("max_lag_steps must be at least 8 and below half n_steps.")
        if not 0.55 <= self.calibration_fraction <= 0.85:
            raise ValueError("calibration_fraction must leave both training and future periods.")
        if self.primary_tracer not in _TRACERS:
            raise ValueError(f"primary_tracer must be one of {_TRACERS!r}.")
        if self.young_threshold_days <= 0.0:
            raise ValueError("young_threshold_days must be positive.")
        if self.input_noise_std < 0.0 or self.output_noise_std < 0.0:
            raise ValueError("Noise scales cannot be negative.")
        if self.minimum_calibration_points < 8:
            raise ValueError("minimum_calibration_points must be at least 8.")


@dataclass(frozen=True)
class EdgeParticleKernel:
    """Raw particle travel times and their normalized causal lag histogram."""

    edge: _EDGE
    particle_travel_times_days: np.ndarray
    lag_days: np.ndarray
    mass: np.ndarray

    def __post_init__(self) -> None:
        edge = (str(self.edge[0]), str(self.edge[1]))
        particles = _readonly(self.particle_travel_times_days)
        lags = _readonly(self.lag_days)
        mass = _readonly(self.mass)
        if particles.size == 0 or np.any(particles < 0.0):
            raise ValueError("Particle travel times must be non-empty and causal.")
        if lags.size == 0 or np.any(lags < 0.0) or np.any(np.diff(lags) < 0.0):
            raise ValueError("Lag grid must be non-empty, non-negative, and ordered.")
        if mass.shape != lags.shape or np.any(mass < 0.0):
            raise ValueError("Kernel mass must match the causal lag grid and be non-negative.")
        if not np.isclose(float(mass.sum()), 1.0, atol=1e-12):
            raise ValueError("Each particle-derived kernel must conserve unit mass.")
        object.__setattr__(self, "edge", edge)
        object.__setattr__(self, "particle_travel_times_days", particles)
        object.__setattr__(self, "lag_days", lags)
        object.__setattr__(self, "mass", mass)


@dataclass(frozen=True)
class ParticleTTDTruth:
    """Scoring-only latent state; never pass this object to an estimator."""

    config: ParticleTTDConfig
    true_edges: tuple[_EDGE, ...]
    edge_kernels: Mapping[str, EdgeParticleKernel]
    node_age_particles: Mapping[str, np.ndarray]
    node_responses: Mapping[str, Mapping[str, np.ndarray]]
    input_signals: Mapping[str, Mapping[str, np.ndarray]]
    local_recharge_fraction: Mapping[str, float]
    upstream_mixing_fraction: Mapping[str, Mapping[str, float]]
    commitment: str
    provenance: Mapping[str, object] = field(default_factory=dict)

    def __post_init__(self) -> None:
        ordered_edges = tuple((str(start), str(end)) for start, end in self.true_edges)
        kernels = MappingProxyType({str(key): value for key, value in self.edge_kernels.items()})
        ages = MappingProxyType({str(key): _readonly(value) for key, value in self.node_age_particles.items()})
        responses = _frozen_nested_array_mapping(self.node_responses)
        inputs = _frozen_nested_array_mapping(self.input_signals)
        local = _frozen_float_mapping(self.local_recharge_fraction)
        upstream = MappingProxyType(
            {str(node): _frozen_float_mapping(weights) for node, weights in self.upstream_mixing_fraction.items()}
        )
        if not self.commitment or len(self.commitment) != 64:
            raise ValueError("Truth requires a SHA-256 commitment.")
        object.__setattr__(self, "true_edges", ordered_edges)
        object.__setattr__(self, "edge_kernels", kernels)
        object.__setattr__(self, "node_age_particles", ages)
        object.__setattr__(self, "node_responses", responses)
        object.__setattr__(self, "input_signals", inputs)
        object.__setattr__(self, "local_recharge_fraction", local)
        object.__setattr__(self, "upstream_mixing_fraction", upstream)
        object.__setattr__(self, "provenance", MappingProxyType(dict(self.provenance)))


