"""Independent multilayer MODFLOW 6 / MODPATH 7 generator for the programme gate.

The v3 family is deliberately independent of the historical M7 v1/v2 files.
It constructs a two-layer flow field, launches four particles, and then forms
an observed network from particle-mixture junctions.  The junction mapping is
part of the synthetic experiment: two upstream alternatives branch and then
mix at downstream observation nodes.  MODFLOW supplies the hydraulic field
and MODPATH supplies the travel-time records; chemistry and tracer panels are
generated by separate equations below.

Only ``observations`` are intended for the inference stage.  Ages, edges,
particle routes, and process labels are sealed in separate truth fields.
This module intentionally imports no HydroSheaf code and does not import either
historical MODFLOW generator.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field
import hashlib
from pathlib import Path
import subprocess
from typing import Dict, List, Mapping, Sequence, Tuple

import flopy
import numpy as np
from scipy.ndimage import gaussian_filter


ION_ORDER = [
    "Ca",
    "Mg",
    "Na",
    "K",
    "HCO3",
    "Cl",
    "SO4",
    "NO3",
    "F",
    "Fe",
    "PO4",
    "SiO2",
]


@dataclass(frozen=True)
class IndependentAquiferV3:
    """Blind observations plus sealed truth for one v3 synthetic case."""

    seed: int
    observations: Tuple[Dict[str, object], ...]
    true_edges: Tuple[Tuple[str, str], ...]
    true_ages_years: Dict[str, float]
    true_processes: Dict[str, str]
    pathline_rows: Tuple[Dict[str, object], ...]
    provenance: Dict[str, object]
    true_nuisance: Mapping[str, float] = field(default_factory=dict)
    true_recharge_isotopes: Mapping[str, Mapping[str, float]] = field(
        default_factory=dict
    )
    true_age_components: Mapping[str, Tuple[float, ...]] = field(default_factory=dict)
    true_mixture_weights: Mapping[str, Tuple[float, ...]] = field(default_factory=dict)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _version(executable: Path) -> str:
    """Return an executable version without allowing provenance to hang.

    Some local MODPATH builds finish the version output but do not terminate
    promptly when invoked with ``-v``.  Version capture is provenance only; it
    must never prevent the actual forward model or validation package from
    completing.
    """

    try:
        completed = subprocess.run(
            [str(executable), "-v"],
            check=False,
            capture_output=True,
            text=True,
            timeout=15.0,
        )
    except subprocess.TimeoutExpired:
        return "version_probe_timeout"
    text = (completed.stdout or completed.stderr).strip()
    return text.splitlines()[0] if text else "version_unavailable"


def _build_multilayer_flow_model(
    seed: int,
    workspace: Path,
    mf6_executable: Path,
) -> Tuple[object, np.ndarray, Dict[str, object]]:
    """Build and execute a new two-layer heterogeneous flow model."""

    rng = np.random.default_rng(int(seed) + 31_000)
    nlay, nrow, ncol = 2, 12, 24
    delr = delc = 100.0
    top = 80.0
    botm = [65.0, 0.0]
    sim = flopy.mf6.MFSimulation(
        sim_name=f"m7v3_flow_{seed}",
        sim_ws=workspace,
        exe_name=str(mf6_executable),
    )
    flopy.mf6.ModflowTdis(
        sim,
        time_units="DAYS",
        nper=1,
        perioddata=[(1.0, 1, 1.0)],
    )
    ims = flopy.mf6.ModflowIms(
        sim,
        complexity="MODERATE",
        outer_dvclose=1e-9,
        inner_dvclose=1e-9,
        outer_maximum=300,
        inner_maximum=400,
    )
    gwf = flopy.mf6.ModflowGwf(
        sim,
        modelname="gwf_v3",
        save_flows=True,
    )
    sim.register_ims_package(ims, [gwf.name])
    flopy.mf6.ModflowGwfdis(
        gwf,
        nlay=nlay,
        nrow=nrow,
        ncol=ncol,
        delr=delr,
        delc=delc,
        top=top,
        botm=botm,
    )
    flopy.mf6.ModflowGwfic(gwf, strt=[56.0, 44.0])

    raw_log_k = gaussian_filter(
        rng.normal(0.0, 0.85, size=(nlay, nrow, ncol)),
        sigma=(0.7, 1.1, 1.4),
        mode="reflect",
    )
    layer_scale = np.asarray([8.5, 3.4], dtype=float)[:, None, None]
    hydraulic_k = np.clip(layer_scale * np.exp(raw_log_k), 0.25, 32.0)
    # A diagonal upper-layer barrier and a lower-layer preferential corridor
    # create genuinely different residence-time and vertical-exchange regimes.
    for row in range(nrow):
        col = 5 + ((2 * row + int(seed)) % 9)
        hydraulic_k[0, max(0, row - 1) : min(nrow, row + 2), col] *= 0.16
        hydraulic_k[1, max(0, row - 1) : min(nrow, row + 2), col + 4] *= 2.2
    vertical_k = np.clip(
        np.stack(
            [0.16 * np.exp(raw_log_k[0] * 0.15), 0.07 * np.exp(raw_log_k[1] * 0.15)]
        ),
        0.02,
        0.45,
    )
    flopy.mf6.ModflowGwfnpf(
        gwf,
        icelltype=0,
        k=hydraulic_k,
        k33=vertical_k,
        save_specific_discharge=True,
    )

    left_upper = 64.0 + 0.18 * (int(seed) % 5)
    right_upper = 48.0
    left_lower = 58.0 + 0.12 * (int(seed) % 4)
    right_lower = 28.0
    constant_heads = []
    for row in range(nrow):
        constant_heads.extend(
            [
                ((0, row, 0), left_upper),
                ((0, row, ncol - 1), right_upper),
                ((1, row, 0), left_lower),
                ((1, row, ncol - 1), right_lower),
            ]
        )
    flopy.mf6.ModflowGwfchd(
        gwf,
        stress_period_data=constant_heads,
        save_flows=True,
    )
    flopy.mf6.ModflowGwfoc(
        gwf,
        head_filerecord="gwf_v3.hds",
        budget_filerecord="gwf_v3.cbc",
        saverecord=[("HEAD", "ALL"), ("BUDGET", "ALL")],
    )
    sim.write_simulation(silent=True)
    success, report = sim.run_simulation(silent=True, report=True)
    if not success:
        raise RuntimeError("MODFLOW 6 v3 failed:\n" + "\n".join(report[-20:]))
    heads = flopy.utils.HeadFile(workspace / "gwf_v3.hds").get_data()
    vertical_exchange_abs_flow_sum = _solver_vertical_exchange_abs_flow(
        workspace,
        nrow=nrow,
        ncol=ncol,
    )
    metadata: Dict[str, object] = {
        "nlay": nlay,
        "nrow": nrow,
        "ncol": ncol,
        "delr_m": delr,
        "delc_m": delc,
        "porosity": 0.27,
        "left_heads_m": [left_upper, left_lower],
        "right_heads_m": [right_upper, right_lower],
        "hydraulic_k_min_m_day": float(hydraulic_k.min()),
        "hydraulic_k_max_m_day": float(hydraulic_k.max()),
        "vertical_k_min_m_day": float(vertical_k.min()),
        "vertical_k_max_m_day": float(vertical_k.max()),
        "heterogeneous_k": True,
        "layered_flow": True,
        "vertical_exchange": True,
        "vertical_exchange_abs_flow_sum": vertical_exchange_abs_flow_sum,
        "flow_model_family": "two_layer_diagonal_barrier_corridor",
    }
    return gwf, heads, metadata


def _run_multilayer_pathlines(
    seed: int,
    workspace: Path,
    gwf: object,
    mp7_executable: Path,
) -> List[np.ndarray]:
    """Run MODPATH from four sources in both layers."""

    nrow = int(gwf.modelgrid.nrow)
    ncol = int(gwf.modelgrid.ncol)
    layer_size = nrow * ncol
    nodes = [
        2 * ncol + 1,
        8 * ncol + 1,
        layer_size + 3 * ncol + 1,
        layer_size + 9 * ncol + 1,
    ]
    model_name = f"m7v3_mp_{seed}"
    mp = flopy.modpath.Modpath7.create_mp7(
        modelname=model_name,
        trackdir="forward",
        flowmodel=gwf,
        model_ws=workspace,
        rowcelldivisions=1,
        columncelldivisions=1,
        layercelldivisions=1,
        nodes=nodes,
        porosity=0.27,
        exe_name=str(mp7_executable),
    )
    mp.write_input()
    success, report = mp.run_model(silent=True, report=True)
    if not success:
        raise RuntimeError("MODPATH 7 v3 failed:\n" + "\n".join(report[-20:]))
    pathline_file = flopy.utils.PathlineFile(workspace / f"{model_name}.mppth")
    return [np.sort(path, order="time") for path in pathline_file.get_alldata()]


def _solver_vertical_exchange_abs_flow(
    workspace: Path,
    *,
    nrow: int,
    ncol: int,
) -> float:
    """Read MODFLOW's connection budget and quantify cross-layer flow."""

    budget_path = workspace / "gwf_v3.cbc"
    grid_path = workspace / "gwf_v3.dis.grb"
    try:
        budget = flopy.utils.CellBudgetFile(budget_path, precision="double")
        flowja_records = budget.get_data(text="FLOW-JA-FACE")
        flowja = np.asarray(flowja_records[0], dtype=float).reshape(-1)
        grid = flopy.mf6.utils.MfGrdFile(str(grid_path))
        layer_offset = int(nrow) * int(ncol)
        vertical_abs_sum = 0.0
        for node in range(len(grid.ia) - 1):
            for connection_index in range(
                int(grid.ia[node]), int(grid.ia[node + 1])
            ):
                neighbour = int(grid.ja[connection_index])
                if abs(neighbour - node) == layer_offset:
                    vertical_abs_sum += abs(float(flowja[connection_index]))
    except (OSError, IndexError, KeyError, TypeError, ValueError) as exc:
        raise RuntimeError("MODFLOW v3 vertical-flow budget could not be audited.") from exc
    if not np.isfinite(vertical_abs_sum) or vertical_abs_sum <= 0.0:
        raise RuntimeError("MODFLOW v3 produced no nonzero interlayer flow.")
    return float(vertical_abs_sum)


def _cell_from_path_record(
    record: np.void,
    *,
    nlay: int,
    nrow: int,
    ncol: int,
    delr: float,
    delc: float,
) -> Tuple[int, int, int]:
    """Recover a bounded layer/row/column from a MODPATH record."""

    x = max(0.0, float(record["x"]))
    y = max(0.0, float(record["y"]))
    row = min(nrow - 1, max(0, nrow - 1 - int(np.floor(y / delc))))
    col = min(ncol - 1, max(0, int(np.floor(x / delr))))
    node = int(record["node"]) if "node" in (record.dtype.names or ()) else 0
    total = nlay * nrow * ncol
    node = min(total - 1, max(0, node))
    layer = node // (nrow * ncol)
    return layer, row, col


def _reaction_step(
    chemistry: np.ndarray,
    travel_years: float,
    process: str,
    rng: np.random.Generator,
) -> np.ndarray:
    """Advance a bounded nonlinear major-ion state by one reaction segment."""

    state = chemistry.copy()
    dt = max(0.05, float(travel_years))
    index = {ion: idx for idx, ion in enumerate(ION_ORDER)}
    if process == "carbonate_weathering":
        extent = 0.30 * (1.0 - np.exp(-dt / 7.5)) * np.exp(-state[index["Ca"]] / 4.0)
        state[index["Ca"]] += extent
        state[index["Mg"]] += 0.25 * extent
        state[index["HCO3"]] += 1.65 * extent
    elif process == "silicate_weathering":
        extent = 0.085 * np.log1p(dt) * np.exp(-state[index["SiO2"]] / 8.0)
        state[index["Na"]] += 0.75 * extent
        state[index["K"]] += 0.20 * extent
        state[index["Ca"]] += 0.10 * extent
        state[index["HCO3"]] += 0.80 * extent
        state[index["SiO2"]] += 1.45 * extent
    elif process == "denitrification":
        consumed = state[index["NO3"]] * min(0.86, 1.0 - np.exp(-0.075 * dt))
        state[index["NO3"]] -= consumed
        state[index["HCO3"]] += 0.68 * consumed
    elif process == "sulfate_reduction":
        consumed = state[index["SO4"]] * min(0.68, 1.0 - np.exp(-0.048 * dt))
        state[index["SO4"]] -= consumed
        state[index["HCO3"]] += 1.55 * consumed
        state[index["Fe"]] += 0.022 * consumed
    elif process == "iron_reduction":
        extent = 0.020 * np.log1p(dt) * np.exp(-4.5 * state[index["NO3"]])
        state[index["Fe"]] += extent
        state[index["HCO3"]] += 0.88 * extent
    elif process == "carbonate_precipitation":
        extent = min(
            0.38 * state[index["Ca"]],
            max(0.0, 0.015 * dt * (state[index["Ca"]] * state[index["HCO3"]] - 0.70)),
        )
        state[index["Ca"]] -= extent
        state[index["HCO3"]] -= min(0.85 * state[index["HCO3"]], 1.75 * extent)
    else:
        raise ValueError(f"Unknown v3 reaction: {process}")
    state *= rng.lognormal(0.0, 0.016 + 0.0012 * dt, state.size)
    state[index["Cl"]] *= rng.lognormal(0.0, 0.009)
    return np.clip(state, 1e-6, None)


def _stable_isotopes(
    x_m: float,
    y_m: float,
    layer: int,
    rng: np.random.Generator,
) -> Dict[str, float]:
    """Draw conservative recharge isotopes from spatially varying endmembers."""

    d18o = (
        -3.35
        - 0.24 * float(x_m) / 1000.0
        + 0.15 * float(y_m) / 1000.0
        - 0.35 * int(layer)
        + float(rng.normal(0.0, 0.07))
    )
    d2h = 7.9 * d18o + 9.5 + float(rng.normal(0.0, 1.2))
    return {
        "d18O_permil": float(d18o),
        "d2H_permil": float(d2h),
        "deuterium_excess_permil": float(d2h - 8.0 * d18o),
    }


def _reaction_isotopes(process_history: Sequence[str]) -> Dict[str, float]:
    carbonate_fraction = 0.0
    silicate_fraction = 0.0
    d13c_shift = 0.0
    for process in process_history:
        if process == "carbonate_weathering":
            carbonate_fraction += 0.38 * (1.0 - carbonate_fraction)
        elif process == "silicate_weathering":
            silicate_fraction += 0.28 * (1.0 - silicate_fraction)
        elif process == "carbonate_precipitation":
            d13c_shift -= 0.60
        elif process == "sulfate_reduction":
            d13c_shift -= 1.35
        elif process == "iron_reduction":
            d13c_shift -= 0.75
    return {
        "d13C_permil": float(-23.5 + 22.5 * carbonate_fraction + d13c_shift),
        "sr87_sr86": float(0.7082 + 0.0115 * silicate_fraction),
    }


def _tracer_panel(
    age_years: float,
    process_history: Sequence[str],
    rng: np.random.Generator,
) -> Dict[str, float]:
    """Generate non-negative age and redox tracers from an independent panel."""

    age = max(0.0, float(age_years))
    reducing = sum(
        weight
        for process, weight in {
            "denitrification": 0.35,
            "sulfate_reduction": 1.0,
            "iron_reduction": 0.60,
        }.items()
        if process in process_history
    )
    tritium = 6.8 * np.exp(-age / 18.5) + 0.42 * np.exp(-((age - 31.0) / 8.5) ** 2)
    argon39 = 104.0 * np.exp(-np.log(2.0) * age / 275.0)
    c14 = 98.0 * np.exp(-np.log(2.0) * age / 5730.0) * np.exp(-0.055 * reducing)
    recharge_year = 2025.5 - age
    cfc11 = 270.0 / (1.0 + np.exp(-(recharge_year - 1974.0) / 6.8))
    cfc11 *= np.exp(-0.48 * reducing)
    cfc12 = 540.0 / (1.0 + np.exp(-(recharge_year - 1976.0) / 8.0))
    cfc113 = 82.0 / (1.0 + np.exp(-(recharge_year - 1983.0) / 5.4))
    sf6 = 11.0 / (1.0 + np.exp(-(recharge_year - 2004.0) / 10.0))
    he4 = 4.2e-8 + 1.15e-10 * age
    he3 = 0.88 * max(0.0, tritium) * (np.exp(np.log(2.0) * min(age, 75.0) / 12.32) - 1.0)
    values = {
        "tritium_TU": tritium,
        "argon39_pmc": argon39,
        "c14_pmc": c14,
        "cfc11_pptv": cfc11,
        "cfc12_pptv": cfc12,
        "cfc113_pptv": cfc113,
        "sf6_pptv": sf6,
        "he4_ccpg": he4,
        "h3_he3_TU": he3,
    }
    noisy: Dict[str, float] = {}
    for key, value in values.items():
        if key in {"tritium_TU", "argon39_pmc", "c14_pmc"}:
            perturbed = float(value + rng.normal(0.0, {"tritium_TU": 0.08, "argon39_pmc": 1.0, "c14_pmc": 0.55}[key]))
        else:
            perturbed = float(value * rng.lognormal(0.0, 0.025))
        noisy[key] = max(0.02 if key != "he4_ccpg" else 0.0, perturbed)
    return noisy


def _particle_milestone(
    path: np.ndarray,
    *,
    particle_index: int,
    heads: np.ndarray,
    metadata: Mapping[str, object],
    rng: np.random.Generator,
    process_path: Sequence[str],
) -> Tuple[List[Dict[str, object]], Dict[str, float]]:
    """Convert one MODPATH trajectory into four blind candidate observations."""

    nlay = int(metadata["nlay"])
    nrow = int(metadata["nrow"])
    ncol = int(metadata["ncol"])
    delr = float(metadata["delr_m"])
    delc = float(metadata["delc_m"])
    milestones = (2, 8, 14, 20)
    base = np.asarray(
        [0.58, 0.25, 0.46, 0.06, 1.48, 0.23, 0.44, 0.32, 0.008, 0.003, 0.005, 0.52],
        dtype=float,
    )
    chemistry = base * rng.lognormal(0.0, 0.07, base.size)
    previous_time = 0.0
    process_history: List[str] = []
    records: List[Dict[str, object]] = []
    recharge_isotopes: Dict[str, float] | None = None
    for milestone_index, column in enumerate(milestones):
        eligible = path[np.floor(np.maximum(path["x"], 0.0) / delr).astype(int) >= column]
        if eligible.size == 0:
            raise RuntimeError(
                f"v3 particle {particle_index} did not reach milestone column {column}."
            )
        record = eligible[0]
        layer, row, actual_column = _cell_from_path_record(
            record,
            nlay=nlay,
            nrow=nrow,
            ncol=ncol,
            delr=delr,
            delc=delc,
        )
        elapsed_days = float(record["time"])
        age_years = 0.9 + elapsed_days / 365.25
        if milestone_index:
            process = str(process_path[milestone_index - 1])
            chemistry = _reaction_step(
                chemistry,
                (elapsed_days - previous_time) / 365.25,
                process,
                rng,
            )
            process_history.append(process)
        x = float(record["x"])
        y = float(record["y"])
        if recharge_isotopes is None:
            recharge_isotopes = _stable_isotopes(x, y, layer, rng)
        reaction = _reaction_isotopes(process_history)
        tracers = _tracer_panel(age_years, process_history, rng)
        records.append(
            {
                "particle": particle_index,
                "milestone": milestone_index,
                "x_m": x,
                "y_m": y,
                "layer_zero_based": layer,
                "row_zero_based": row,
                "column_zero_based": actual_column,
                "head_m": float(heads[layer, row, actual_column]),
                "age_years": age_years,
                "chemistry": chemistry.copy(),
                "stable": dict(recharge_isotopes),
                "reaction": reaction,
                "tracers": tracers,
                "process": "source" if not milestone_index else str(process_path[milestone_index - 1]),
                "modpath_node_zero_based": int(record["node"]),
                "travel_time_days": elapsed_days,
            }
        )
        previous_time = elapsed_days
    return records, dict(recharge_isotopes or {})


def generate_independent_aquifer_v3(
    seed: int,
    workspace: Path,
    mf6_executable: Path,
    mp7_executable: Path,
) -> IndependentAquiferV3:
    """Execute the v3 simulators and return observations with sealed truth."""

    workspace = Path(workspace)
    workspace.mkdir(parents=True, exist_ok=True)
    mf6_executable = Path(mf6_executable).resolve()
    mp7_executable = Path(mp7_executable).resolve()
    if not mf6_executable.exists() or not mp7_executable.exists():
        raise FileNotFoundError("Both official mf6 and mp7 executables are required.")

    rng = np.random.default_rng(int(seed) + 77_000)
    gwf, heads, metadata = _build_multilayer_flow_model(int(seed), workspace, mf6_executable)
    pathlines = _run_multilayer_pathlines(int(seed), workspace, gwf, mp7_executable)
    if len(pathlines) != 4:
        raise RuntimeError(f"MODPATH v3 returned {len(pathlines)} paths; expected four.")
    process_paths = (
        ("carbonate_weathering", "carbonate_precipitation", "silicate_weathering"),
        ("denitrification", "sulfate_reduction", "iron_reduction"),
        ("silicate_weathering", "carbonate_weathering", "denitrification"),
        ("carbonate_weathering", "sulfate_reduction", "carbonate_precipitation"),
    )
    particle_records: List[List[Dict[str, object]]] = []
    recharge_truth: Dict[str, Dict[str, float]] = {}
    for particle_index, path in enumerate(pathlines):
        records, recharge = _particle_milestone(
            path,
            particle_index=particle_index,
            heads=heads,
            metadata=metadata,
            rng=rng,
            process_path=process_paths[particle_index],
        )
        particle_records.append(records)
        recharge_truth[f"particle_{particle_index}"] = recharge

    # The four paths create two upstream alternatives, two intermediate
    # branches, and two downstream mixing observations.
    assignments = (
        ("A", "C", "E", "F"),
        ("A", "D", "E", "F"),
        ("B", "D", "E", "F"),
        ("B", "C", "E", "F"),
    )
    particle_release_weights = (0.30, 0.22, 0.26, 0.22)
    node_order = ("A", "B", "C", "D", "E", "F")
    grouped: Dict[str, List[Dict[str, object]]] = {node: [] for node in node_order}
    pathline_rows: List[Dict[str, object]] = []
    for particle_index, records in enumerate(particle_records):
        for record, node in zip(records, assignments[particle_index]):
            grouped[node].append(record)
            pathline_rows.append(
                {
                    "particle": int(record["particle"]),
                    "milestone": int(record["milestone"]),
                    "node_id": f"V3_{seed}_{node}",
                    "modpath_node_zero_based": int(record["modpath_node_zero_based"]),
                    "row_zero_based": int(record["row_zero_based"]),
                    "column_zero_based": int(record["column_zero_based"]),
                    "layer_zero_based": int(record["layer_zero_based"]),
                    "x_m": float(record["x_m"]),
                    "y_m": float(record["y_m"]),
                    "travel_time_days": float(record["travel_time_days"]),
                    "age_years": float(record["age_years"]),
                }
            )

    observations: List[Dict[str, object]] = []
    true_ages: Dict[str, float] = {}
    true_age_components: Dict[str, Tuple[float, ...]] = {}
    true_mixture_weights: Dict[str, Tuple[float, ...]] = {}
    for node in node_order:
        entries = grouped[node]
        if not entries:
            raise RuntimeError(f"v3 node {node} has no particle support.")
        node_id = f"V3_{seed}_{node}"
        x = float(np.mean([float(entry["x_m"]) for entry in entries]))
        y = float(np.mean([float(entry["y_m"]) for entry in entries]))
        head = float(np.mean([float(entry["head_m"]) for entry in entries]))
        layer_values = [int(entry["layer_zero_based"]) for entry in entries]
        layer = Counter(layer_values).most_common(1)[0][0]
        raw_weights = np.asarray(
            [particle_release_weights[int(entry["particle"])] for entry in entries],
            dtype=float,
        )
        weights = raw_weights / float(raw_weights.sum())
        age_components = tuple(float(entry["age_years"]) for entry in entries)
        age_years = float(
            np.average(np.asarray(age_components, dtype=float), weights=weights)
        )
        chemistry = np.average(
            np.stack([np.asarray(entry["chemistry"], dtype=float) for entry in entries]),
            axis=0,
            weights=weights,
        )
        stable = {
            key: float(
                np.average(
                    [float(entry["stable"][key]) for entry in entries],
                    weights=weights,
                )
            )
            for key in ("d18O_permil", "d2H_permil", "deuterium_excess_permil")
        }
        reaction = {
            key: float(
                np.average(
                    [float(entry["reaction"][key]) for entry in entries],
                    weights=weights,
                )
            )
            for key in ("d13C_permil", "sr87_sr86")
        }
        tracer_keys = tuple(entries[0]["tracers"].keys())
        tracers = {
            key: float(
                np.average(
                    [float(entry["tracers"][key]) for entry in entries],
                    weights=weights,
                )
            )
            for key in tracer_keys
        }
        sample: Dict[str, object] = {
            "site_id": node_id,
            "sample_id": node_id,
            "x_m": x,
            "y_m": y,
            "lat": 7.0 + y / 111_000.0,
            "lon": -1.5 + x / 111_000.0,
            "head_meas": head + float(rng.normal(0.0, 0.035)),
            "hydraulic_head": head + float(rng.normal(0.0, 0.035)),
            "elevation": head + (18.0 if layer == 0 else 8.0),
            "screen_depth": 18.0 if layer == 0 else 42.0,
            "well_depth": 32.0 if layer == 0 else 58.0,
            "aquifer_unit": "external_modflow_v3_layered_mixing",
            "aquifer_layer": int(layer) + 1,
            "pH": float(
                np.clip(
                    6.70 + 0.020 * age_years + (0.38 if layer else 0.0)
                    + float(rng.normal(0.0, 0.035)),
                    6.2,
                    8.8,
                )
            ),
            "temp_c": float(25.2 - 0.015 * age_years + float(rng.normal(0.0, 0.25))),
            "sample_date": 2025.5,
            **stable,
            **reaction,
            **tracers,
        }
        for ion_index, ion in enumerate(ION_ORDER):
            sample[ion] = float(max(1e-6, chemistry[ion_index]))
        observations.append(sample)
        true_ages[node_id] = age_years
        true_age_components[node_id] = age_components
        true_mixture_weights[node_id] = tuple(float(value) for value in weights)

    edge_votes: Dict[Tuple[str, str], List[str]] = {}
    for particle_index, sequence in enumerate(assignments):
        for milestone_index in range(1, len(sequence)):
            source = f"V3_{seed}_{sequence[milestone_index - 1]}"
            target = f"V3_{seed}_{sequence[milestone_index]}"
            edge_votes.setdefault((source, target), []).append(
                process_paths[particle_index][milestone_index - 1]
            )
    true_edges = tuple(edge_votes)
    true_processes = {
        f"{source}->{target}": Counter(votes).most_common(1)[0][0]
        for (source, target), votes in edge_votes.items()
    }
    provenance: Dict[str, object] = {
        "generator": "independent_multilayer_modflow_modpath_mixing_v3",
        "imports_hydrosheaf": False,
        "mf6_executable": str(mf6_executable),
        "mf6_sha256": _sha256(mf6_executable),
        "mf6_version": _version(mf6_executable),
        "mp7_executable": str(mp7_executable),
        "mp7_sha256": _sha256(mp7_executable),
        "mp7_version": _version(mp7_executable),
        "flopy_version": flopy.__version__,
        "chemistry_generator": "independent nonlinear layered reaction equations",
        "tracer_generator": "independent analytic age and redox panel",
        "topology_generator": "four MODPATH particles aggregated into branch-merge mixtures",
        "topology_nodes": list(node_order),
        "topology_assignments": [list(sequence) for sequence in assignments],
        "topology_branch_nodes": [f"V3_{seed}_A", f"V3_{seed}_B"],
        "topology_merge_nodes": [f"V3_{seed}_C", f"V3_{seed}_D", f"V3_{seed}_E"],
        "particle_release_weights": list(particle_release_weights),
        "mixture_age_target": (
            "normalized fixed particle-release-weighted mean; component ages and "
            "weights are sealed outside observations"
        ),
        "mixture_node_support_counts": {
            node: len(grouped[node]) for node in node_order
        },
        "pathline_layer_transitions": {
            str(particle_index): sum(
                int(left["layer_zero_based"]) != int(right["layer_zero_based"])
                for left, right in zip(
                    particle_records[particle_index],
                    particle_records[particle_index][1:],
                )
            )
            for particle_index in range(len(particle_records))
        },
        "truth_sealed_fields": [
            "true_edges",
            "true_ages_years",
            "true_processes",
            "pathline_rows",
            "true_recharge_isotopes",
            "true_age_components",
            "true_mixture_weights",
        ],
        **metadata,
    }
    return IndependentAquiferV3(
        seed=int(seed),
        observations=tuple(observations),
        true_edges=true_edges,
        true_ages_years=true_ages,
        true_processes=true_processes,
        pathline_rows=tuple(pathline_rows),
        provenance=provenance,
        true_recharge_isotopes=recharge_truth,
        true_age_components=true_age_components,
        true_mixture_weights=true_mixture_weights,
    )


