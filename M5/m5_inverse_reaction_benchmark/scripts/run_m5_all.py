"""Run the M5 controlled synthetic benchmark without field branches.

Historical M5 field tables and publication figures are not regenerated by
this entry point because they contain results from the retired field workflow.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import subprocess
import sys

SCRIPT_DIR = Path(__file__).resolve().parent


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=None)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--reuse-synthetic", action="store_true")
    mode.add_argument("--reuse-phreeqc", action="store_true")
    args = parser.parse_args()
    command = [sys.executable, str(SCRIPT_DIR / "run_m5_inverse_reaction_benchmark.py")]
    if args.output_dir is not None:
        command.extend(["--output-dir", str(args.output_dir)])
    if args.reuse_synthetic:
        command.append("--reuse-synthetic")
    if args.reuse_phreeqc:
        command.append("--reuse-phreeqc")
    subprocess.run(command, check=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
